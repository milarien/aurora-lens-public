"""Fail closed on any uncontracted shared-program or installation difference.

Local CI/builds check the complete program against the same immutable contract.
A release additionally checks both explicit Git revisions, never a file sample.
No file is copied and no contract is generated by this verifier.
"""
from __future__ import annotations

import argparse
import ast
import hashlib
import io
import json
from pathlib import Path
import subprocess
import tarfile

CONTRACT = "release/shared-program-contract.json"


def digest(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def normalize(data: bytes) -> bytes:
    try:
        data.decode("utf-8")
    except UnicodeDecodeError:
        return data
    return data.replace(b"\r\n", b"\n")


def ignored(path: str) -> bool:
    return any(part in {"__pycache__", ".claude", ".agents", ".codex"} for part in Path(path).parts) or path.endswith((".pyc", ".pyo", ".bak"))


def git(repo: Path, *args: str) -> bytes:
    return subprocess.check_output(["git", "-C", str(repo), *args])


def projection(data: bytes, rules: dict, role: str) -> tuple[bytes, list[str]]:
    """Only exact reviewed installation nodes may differ inside a shared file.

    All other AST nodes, including every governance branch and literal, remain
    compared. Approved nodes are pinned per role; this is not a function-ignore
    list. Only comments/formatting are normalized in a projected Python file.
    """
    tree = ast.parse(data.decode("utf-8-sig"))
    errors = []
    for selector, rule in sorted(rules.items()):
        if not rule.get("reason"):
            errors.append(f"undocumented installation section: {selector}")
        parts = selector.split("/")
        body = tree.body
        selected = None
        for part in parts:
            kind, _, name = part.partition(":")
            if kind == "docstring":
                selected = body[0] if body and isinstance(body[0], ast.Expr) and isinstance(body[0].value, ast.Constant) and isinstance(body[0].value.value, str) else None
            elif kind == "function":
                selected = next((node for node in body if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)) and node.name == name), None)
            elif kind == "assignment":
                selected = next((node for node in body if isinstance(node, ast.Assign) and any(isinstance(target, ast.Name) and target.id == name for target in node.targets)), None)
            else:
                raise ValueError(f"unsupported installation selector: {selector}")
            if selected is None:
                break
            if part != parts[-1]:
                body = selected.body
        actual = digest(ast.dump(selected, include_attributes=False).encode()) if selected is not None else None
        if actual != rule[role]:
            errors.append(f"unapproved {role} installation section: {selector}")
        if selected is not None:
            body.remove(selected)
    return ast.dump(tree, include_attributes=False).encode(), errors


def read_program(repo: Path, role: str, ref: str | None = None) -> tuple[dict, dict[str, bytes], str]:
    raw = git(repo, "show", f"{ref}:{CONTRACT}") if ref else (repo / CONTRACT).read_bytes()
    contract = json.loads(raw)
    roots = contract["program_roots"]
    extras = contract["shared_release_files"]
    if ref:
        available = git(repo, "ls-tree", "-r", "--name-only", "-z", ref).decode().split("\0")
        paths = [p for p in available if p and not ignored(p) and (any(p.startswith(root + "/") for root in roots) or p in extras)]
        archive = git(repo, "archive", "--format=tar", ref, "--", *paths)
        with tarfile.open(fileobj=io.BytesIO(archive)) as tar:
            files = {item.name: tar.extractfile(item).read() for item in tar if item.isfile()}
    else:
        files = {}
        for root in roots:
            for path in (repo / root).rglob("*"):
                rel = path.relative_to(repo).as_posix()
                if path.is_file() and not ignored(rel):
                    files[rel] = path.read_bytes()
        for rel in extras:
            if (repo / rel).is_file():
                files[rel] = (repo / rel).read_bytes()
    return contract, files, digest(normalize(raw))


def verify_files(contract: dict, files: dict[str, bytes], role: str) -> dict:
    errors = []
    shared = contract["shared_files"]
    permitted = contract["permitted_installation_files"]
    if not contract.get("pair_verified"):
        errors.append("shared contract has not passed complete paired verification")
    if set(shared) & set(permitted):
        errors.append("a file cannot be both shared governance and an installation exception")
    expected = set(shared) | {path for path, item in permitted.items() if item[role] is not None}
    for path in sorted(set(files) - expected):
        errors.append(f"uncontracted program file: {path}")
    for path in sorted(expected - set(files)):
        errors.append(f"missing program file: {path}")
    hashes = {}
    for path, data in sorted(files.items()):
        data = normalize(data)
        if path in permitted:
            item = permitted[path]
            if not item.get("reason") or digest(data) != item[role]:
                errors.append(f"unapproved {role} installation file: {path}")
        elif path in shared:
            sections = contract.get("permitted_installation_sections", {}).get(path)
            if sections:
                data, section_errors = projection(data, sections, role)
                errors.extend(f"{path}: {error}" for error in section_errors)
            hashes[path] = digest(data)
            if hashes[path] != shared[path]:
                errors.append(f"shared-program mismatch: {path}")
    core_hash = digest(json.dumps(hashes, sort_keys=True, separators=(",", ":")).encode())
    if core_hash != contract["shared_core_sha256"]:
        errors.append("complete shared-program fingerprint mismatch")
    return {"role": role, "passed": not errors, "shared_core_sha256": core_hash,
            "program_files_checked": len(files), "shared_files_checked": len(hashes),
            "permitted_installation_files": permitted,
            "permitted_installation_sections": contract.get("permitted_installation_sections", {}),
            "errors": errors}


def check(repo: Path, role: str, ref: str | None = None) -> tuple[dict, str]:
    contract, files, contract_hash = read_program(repo, role, ref)
    result = verify_files(contract, files, role)
    result.update(repo=str(repo.resolve()), revision=ref or "working_tree", contract_sha256=contract_hash)
    if ref:
        result["revision"] = git(repo, "rev-parse", ref).decode().strip()
    return result, contract_hash


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repo", type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument("--role", required=True, choices=("private", "public"))
    parser.add_argument("--ref", help="Complete committed program at this Git revision")
    parser.add_argument("--peer", type=Path)
    parser.add_argument("--peer-ref")
    parser.add_argument("--deployed-commit", help="Health-reported commit; must be the explicit private --ref")
    parser.add_argument("--output", type=Path)
    args = parser.parse_args()
    result, contract_hash = check(args.repo, args.role, args.ref)
    results = [result]
    errors = list(result["errors"])
    if args.peer:
        peer, peer_contract = check(args.peer, "public" if args.role == "private" else "private", args.peer_ref)
        results.append(peer)
        errors.extend(peer["errors"])
        if peer_contract != contract_hash:
            errors.append("repository shared-program contracts differ")
        if peer["shared_core_sha256"] != result["shared_core_sha256"]:
            errors.append("complete repository shared-program fingerprints differ")
    if args.deployed_commit and (args.role != "private" or not args.ref or result["revision"] != args.deployed_commit):
        errors.append("deployed commit is not the explicit verified private revision")
    output = {"passed": not errors, "paired_comparison": bool(args.peer),
              "deployed_commit": args.deployed_commit, "results": results, "errors": errors}
    if args.output:
        args.output.write_text(json.dumps(output, indent=2) + "\n", encoding="utf-8")
    print(json.dumps(output, indent=2))
    raise SystemExit(0 if output["passed"] else 1)


if __name__ == "__main__":
    main()
