"""Deterministic epistemic uncertainty analysis over committed PEF state.

Uncertainty is a property of the committed world model, not of text.
This module interrogates PEF state directly — it does not call any LLM.

Detectable uncertainty kinds from current PEF (see CORE_UNCERTAINTY_KINDS):
  conflicting_models   — same subject/predicate with incompatible committed values
  unconfirmed_status   — entities committed as unresolved (resolved=False)
  blocked_access       — retrieval_unresolved items (evidence that could not be admitted)
  missing_observation  — expected observation absent, inconclusive, or pending
                         (requires claim_status="pending" from the extraction layer)
  predictive_uncertainty — outcome depends on an event that has not yet occurred
                           (requires claim_status="pending" on a future-facing claim)
"""

