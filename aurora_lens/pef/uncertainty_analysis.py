_GENERATED_SOURCE_UNTRUSTED_ID_PREFIX = "generated_source_untrusted:"

# Explicit scope-comparison contract for scope_mismatch (four parts).
SCOPE_DIMENSION_ALLOWED: frozenset[str] = frozenset({
    "subject",
    "action_type",
    "domain",
    "jurisdiction",
    "timeframe",
    "consequence_grade",
    "authority_level",
})
SCOPE_COMPARISON_MODES: frozenset[str] = frozenset({
    "exact",
    "subset_allowed",
    "superset_allowed",
})

# Explicit threshold-comparison contract for threshold_not_met (four parts + mode).
THRESHOLD_CONSEQUENCE_GRADES: frozenset[str] = frozenset({
    "minimal",
    "low",
    "moderate",
    "high",
    "critical",
})
THRESHOLD_COMPARISON_MODES: frozenset[str] = frozenset({
    "gte",
    "gt",
    "exact",
})
THRESHOLD_COMPARISON_MODE_DEFAULT = "gte"

# Explicit bridge contract for inferential_gap (four parts + bridge_mode).
INFERENTIAL_BRIDGE_STATUSES: frozenset[str] = frozenset({
    "valid",
    "missing",
    "contradicted",
    "expired",
    "out_of_scope",
})
INFERENTIAL_BRIDGE_MODES: frozenset[str] = frozenset({
    "requires_declared_bridge",
})
INFERENTIAL_BRIDGE_MODE_DEFAULT = "requires_declared_bridge"


def normalize_consequence_grade(raw: Any) -> str | None:
    grade = str(raw or "").strip().lower()
    if grade in THRESHOLD_CONSEQUENCE_GRADES:
        return grade
    return None


def normalize_threshold_comparison_mode(raw: Any) -> str | None:
    mode = str(raw or "").strip().lower()
    if mode in THRESHOLD_COMPARISON_MODES:
        return mode
    return None


def normalize_strength_value(raw: Any) -> float | None:
    if isinstance(raw, (int, float)) and not isinstance(raw, bool):
        return float(raw)
    return None


def threshold_comparison_fails(
    observed_strength: float,
    required_strength: float,
    comparison_mode: str,
) -> bool:
    """Return True when declared strengths fail the comparison under comparison_mode."""
    mode = normalize_threshold_comparison_mode(comparison_mode)
    if mode is None:
        return False
    if mode == "gte":
        return observed_strength < required_strength
    if mode == "gt":
        return observed_strength <= required_strength
    return observed_strength != required_strength


def parse_premises(raw: Any) -> list[str] | None:
    """Parse declared premise list; reject empty or informal shapes."""
    if not isinstance(raw, (list, tuple)):
        return None
    premises: list[str] = []
    for item in raw:
        s = str(item).strip()
        if s and s not in premises:
            premises.append(s)
    return premises if premises else None


def normalize_bridge_status(raw: Any) -> str | None:
    status = str(raw or "").strip().lower()
    if status in INFERENTIAL_BRIDGE_STATUSES:
        return status
    return None


def normalize_inferential_bridge_mode(raw: Any) -> str | None:
    mode = str(raw or "").strip().lower()
    if mode in INFERENTIAL_BRIDGE_MODES:
        return mode
    return None


def bridge_status_indicates_gap(bridge_status: str) -> bool:
    """Return True when declared bridge_status is not valid under v1 contract."""
    status = normalize_bridge_status(bridge_status)
    if status is None:
        return False
    return status != "valid"


def normalize_scope_value_dict(raw: Any) -> dict[str, str] | None:
    """Normalize a scope dict to allowed dimensions with non-empty string values."""
    if not isinstance(raw, dict):
        return None
    out: dict[str, str] = {}
    for key, val in raw.items():
        dim = str(key).strip()
        if dim not in SCOPE_DIMENSION_ALLOWED:
            continue
        s = str(val).strip()
        if s:
            out[dim] = s
    return out if out else None


def parse_scope_dimensions(raw: Any) -> list[str] | None:
    """Parse declared comparison axes; reject unknown or empty lists."""
    if not isinstance(raw, (list, tuple)):
        return None
    dims: list[str] = []
    for item in raw:
        dim = str(item).strip()
        if dim not in SCOPE_DIMENSION_ALLOWED:
            return None
        if dim not in dims:
            dims.append(dim)
    return dims if dims else None


def compare_scope_failure_dimensions(
    required: dict[str, str],
    supported: dict[str, str],
    dimensions: list[str],
    comparison_mode: str,
) -> list[str]:
    """Return dimensions that fail deterministic comparison under comparison_mode.

    v1 applies per-dimension token equality for all three modes. Hierarchical
    subset/superset semantics require explicit partial orders on dimension
    values and are reserved for a later contract extension.
    """
    mode = str(comparison_mode or "").strip().lower()
    if mode not in SCOPE_COMPARISON_MODES:
        return []
    failed: list[str] = []
    for dim in dimensions:
        if required.get(dim) != supported.get(dim):
            failed.append(dim)
    return failed


