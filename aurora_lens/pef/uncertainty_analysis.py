def _reconcile_generated_records(
    pef: PEFState,
    new_uncertainties: list[dict[str, Any]],
) -> None:
    """Drop stale generated records no longer produced this pass.

    Only affects generated records with reserved id prefixes.
    Externally declared uncertainty records are never touched.
    """
    active_ids = {
        str(u.get("id") or "")
        for u in new_uncertainties
        if (
            _is_generated_identity_referent_record(u)
            or _is_generated_stale_record(u)
            or _is_generated_scope_mismatch_record(u)
            or _is_generated_threshold_not_met_record(u)
            or _is_generated_inferential_gap_record(u)
            or _is_generated_source_untrusted_record(u)
        )
    }
    if not pef.open_epistemic_uncertainties:
        return
    pef.open_epistemic_uncertainties = [
        u
        for u in pef.open_epistemic_uncertainties
        if not (
            (
                _is_generated_identity_referent_record(u)
                or _is_generated_stale_record(u)
                or _is_generated_scope_mismatch_record(u)
                or _is_generated_threshold_not_met_record(u)
                or _is_generated_inferential_gap_record(u)
                or _is_generated_source_untrusted_record(u)
            )
            and str(u.get("id") or "") not in active_ids
        )
    ]


def merge_epistemic_uncertainties(
    pef: PEFState,
    new_uncertainties: list[dict[str, Any]],
) -> None:
    """Merge uncertainty records into PEF state without overwriting existing entries.

    Matches by id. A previously resolved entry keeps its status.
    """
    _reconcile_generated_records(pef, new_uncertainties)
    existing_ids: set[str] = {
        str(u.get("id")) for u in pef.open_epistemic_uncertainties
    }
    for u in new_uncertainties:
        uid = str(u.get("id") or "").strip()
        if uid and uid not in existing_ids:
            pef.open_epistemic_uncertainties.append(u)
            existing_ids.add(uid)


