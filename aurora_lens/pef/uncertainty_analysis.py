# ── Uncertainty kind taxonomy ──────────────────────────────────────────
#
# Three distinct sets; keep them separate.
#
# CORE_UNCERTAINTY_KINDS             — generated by pef_uncertainty_analysis() from committed PEF state
# EXTERNAL_ESTABLISHMENT_FAILURE_KINDS — externally declared; never generated by this module;
#                                        no generators yet (Phase 2: vocabulary and recognition only)
# RETRIEVAL_UNRESOLVED_KINDS         — admission-layer artefacts on PEFState.retrieval_unresolved;
#                                      structurally separate, defined in rag_pef_admission.py
#
# VALID_OPEN_EPISTEMIC_KINDS         — union; the full set accepted in
#                                      evidence_state.open_epistemic_uncertainties payloads;
#                                      gate remains permissive and does not reject unknown strings

CORE_UNCERTAINTY_KINDS: frozenset[str] = frozenset({
    "conflicting_models",      # two or more committed sources disagree on the same fact
    "missing_observation",     # expected observation absent, inconclusive, or pending
    "blocked_access",          # evidence cannot be reached or admitted
    "unconfirmed_status",      # current state of a critical entity is unknown or unresolved
    "predictive_uncertainty",  # outcome depends on an event that has not yet occurred
})

EXTERNAL_ESTABLISHMENT_FAILURE_KINDS: frozenset[str] = frozenset({
    "identity_or_referent_unresolved",  # claim cannot attach to a unique entity or referent
    "stale_evidence",                   # evidence exists but is no longer current for this consequence
    "inferential_gap",                  # committed evidence does not support the conclusion
    "threshold_not_met",                # evidence is present but below the required evidential threshold
    "source_untrusted",                 # source fails provenance, authority, or admissibility requirements
    "scope_mismatch",                   # evidence is from a different entity/population/domain/jurisdiction
})

VALID_OPEN_EPISTEMIC_KINDS: frozenset[str] = (
    CORE_UNCERTAINTY_KINDS | EXTERNAL_ESTABLISHMENT_FAILURE_KINDS
)

# Backward-compat alias — prefer CORE_UNCERTAINTY_KINDS in new code.
