def _conflict_description(subject_name: str, relation: str, values: list[str], sources: list[str | None]) -> str:
    named = [s for s in sources if s]
    if named:
        source_clause = " and ".join(named)
        return f"{source_clause} disagree on {subject_name} {relation}."
    vals = " vs. ".join(str(v) for v in values[:3])
    return f"Committed values for {subject_name} {relation} conflict: {vals}."


def _iter_open_unresolved_referent_entries(pef: PEFState) -> list[Any]:
    entries = getattr(pef, "unresolved_referent_registry", None)
    if not isinstance(entries, list):
        return []
    out: list[Any] = []
    for entry in entries:
        if isinstance(entry, dict):
            status = str(entry.get("status") or "").strip()
        else:
            status = str(getattr(entry, "status", "") or "").strip()
        if status == "open":
            out.append(entry)
    return out


def _entry_field(entry: Any, name: str) -> str:
    if hasattr(entry, name):
        return str(getattr(entry, name) or "").strip()
    if isinstance(entry, dict):
        return str(entry.get(name) or "").strip()
    return ""


def _identity_referent_bears_on(entry: Any) -> list[str]:
    blocked_proposition = _entry_field(entry, "blocked_proposition")
    if blocked_proposition:
        return [blocked_proposition]
    head = _entry_field(entry, "head")
    if head:
        return [head]
    span_surface = _entry_field(entry, "span_surface")
    if span_surface:
        return [span_surface]
    token = _entry_field(entry, "token")
    if token:
        return [token]
    entry_id = _entry_field(entry, "entry_id")
    return [entry_id] if entry_id else []


def _identity_referent_description(entry: Any) -> str:
    token = _entry_field(entry, "token") or _entry_field(entry, "span_surface") or "referent"
    blocked = _entry_field(entry, "blocked_proposition")
    if blocked:
        return (
            f"The referent for {token!r} is unresolved in the claim "
            f"{blocked!r}."
        )
    return f"The referent for {token!r} is unresolved."


def _parse_iso_dt(value: str) -> datetime | None:
    s = (value or "").strip()
    if not s:
        return None
    if s.endswith("Z"):
        s = s[:-1] + "+00:00"
    try:
        dt = datetime.fromisoformat(s)
    except ValueError:
        return None
    if dt.tzinfo is None:
        dt = dt.replace(tzinfo=timezone.utc)
    return dt.astimezone(timezone.utc)


def _parse_iso_duration(value: str) -> timedelta | None:
    s = (value or "").strip().upper()
    if not s.startswith("P"):
        return None
    days = 0.0
    hours = 0.0
    minutes = 0.0
    cur = ""
    in_time = False
    for ch in s[1:]:
        if ch == "T":
            in_time = True
            continue
        if ch.isdigit() or ch == ".":
            cur += ch
            continue
        if not cur:
            return None
        try:
            num = float(cur)
        except ValueError:
            return None
        cur = ""
        if ch == "D" and not in_time:
            days += num
        elif ch == "H" and in_time:
            hours += num
        elif ch == "M" and in_time:
            minutes += num
        else:
            return None
    if cur:
        return None
    return timedelta(days=days, hours=hours, minutes=minutes)


